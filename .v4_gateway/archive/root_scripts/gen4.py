import os
f = open('docs/app.js', 'a', encoding='utf-8')
f.write('function updateMode(mode) {\n')
f.write('  const modeMap = { critical: "mode-c", balanced: "mode-b", performance: "mode-p" };\n')
f.write('  const modeDisplay = elements.panels.modeDisplay;\n')
f.write('  if (!modeDisplay) return;\n')
f.write('  if (mode) { modeDisplay.className = "mode-indicator " + (modeMap[mode] || mode); modeDisplay.textContent = mode.toUpperCase(); }\n')
f.write('}\n')
f.write('\n')
f.write('async function updateDashboard() {\n')
f.write('  try {\n')
f.write('    const response = await fetch(TELEMETRY_FEED_URL);\n')
f.write('    if (!response.ok) throw new Error("HTTP " + response.status);\n')
f.write('    const telemetry = await response.json();\n')
f.write('    const effectiveTelemetry = telemetry && telemetry.system_status ? telemetry : bTelemetry;\n')
f.write('    renderRamWidget(effectiveTelemetry, false);\n')
f.write('    renderEnvVectorsWidget(effectiveTelemetry, false);\n')
f.write('    renderRegionalPassportsWidget(effectiveTelemetry, false);\n')
f.write('    renderOsintSignalsWidget(effectiveTelemetry, false);\n')
f.write('    const resourceMode = effectiveTelemetry.ram bization_percent || 0;\n')
f.write('    if (resourceMode > 90) updateMode("critical");\n')
f.write('    else if (resourceMode > 70) updateMode("balanced");\n')
f.write('    else updateMode("performance");\n')
f.write('  } catch (error) {\n')
f.write('    console.error("Failed to fetch telemetry feed:", error);\n')
f.write('    const effectiveTelemetry = bTelemetry;\n')
f.write('    renderRamWidget(effectiveTelemetry, true);\n')
f.write('    renderEnvVectorsWidget(effectiveTelemetry, true);\n')
f.write('    renderRegionalPassportsWidget(effectiveTelemetry, true);\n')
f.write('    renderOsintSignalsWidget(effectiveTelemetry, true);\n')
f.write('    updateMode("performance");\n')
f.write('  }\n')
f.write('}\n')
f.write('\n')
f.write('initElements();\n')
f.write('updateDashboard();\n')
f.write('setInterval(updateDashboard, 15000);\n')
f.write('});\n')
f.close()
print('Chunk 4 written: updateMode and updateDashboard')