    def _format_osint_markdown(self, data: dict) -> str:
        """Format OSINT signal data as a Markdown string."""
        lines = []
        lines.append(f"## 📡 Imperia v4 OSINT Signal")
        lines.append(f"*Generated: {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC')}*")
        lines.append("")

        sig_type = data.get("signal_type", "unknown")
        lines.append(f"**Signal Type:** `{sig_type}`")
        lines.append("")

        if "region_id" in data:
            lines.append(f"**Region:** `{data['region_id']}`")
        lines.append("")

        if "summary" in data:
            lines.append(f"**Summary:** {data['summary']}")
        lines.append("")

        if "confidence" in data:
            lines.append(f"**Confidence:** `{data['confidence']}`")
        lines.append("")

        if "source" in data:
            lines.append(f"**Source:** `{data.get('source', 'unknown')}`")
        lines.append("")

        lines.append("> Generated by Imperia v4 SMM Broadcaster")
        return "\n".join(lines)

