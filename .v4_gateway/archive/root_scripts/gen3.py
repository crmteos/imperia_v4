import os
f = open('docs/app.js', 'a', encoding='utf-8')
f.write('function renderRamWidget(telemetry, isFallback = false) {\n')
f.write('  const ramPercent = elements.panels.ramPercent;\n')
f.write('  const ramUsage = elements.panels.ramUsage;\n')
f.write('  if (!ramPercent || !ramUsage) return;\n')
f.write('  const ramState = telemetry?.ram bization_percent ?? bTelemetry.ram bization_percent;\n')
f.write('  ramPercent.textContent = `${ramState.toFixed(1)}%`;\n')
f.write('  if (ramState > 75) { ramPercent.parentElement.style.color = "#ff6b6b"; updateMode("critical"); }\n')
f.write('  else if (ramState > 50) { ramPercent.parentElement.style.color = "#ffd93d"; updateMode("balanced"); }\n')
f.write('  else { ramPercent.parentElement.style.color = "#6bcb77"; updateMode("performance"); }\n')
f.write('  if (ramUsage) {\n')
f.write('    ramUsage.innerHTML = `<strong>b Utilization:</strong> ${ramState.toFixed(1)}%<br><small>${isFallback ? "Local data" : "Live telemetry"}</small>`;\n')
f.write('  }\n')
f.write('}\n')
f.write('\n')
f.write('function renderEnvVectorsWidget(telemetry, isFallback = false) {\n')
f.write('  const grid = elements.panels.vectorGrid;\n')
f.write('  if (!grid) return;\n')
f.write('  const envVectors = telemetry?.environment_vectors ?? bTelemetry.environment_vectors;\n')
f.write('  const axes = ["E_geo", "E_resource", "E_coherence", "E_temporal"];\n')
f.write('  const labels = ["Geo", "Resource", "Coherence", "Temporal"];\n')
f.write('  grid.innerHTML = "";\n')
f.write('  axes.forEach((axis, i) => {\n')
f.write('    const magnitude = (envVectors[axis] && envVectors[axis].magnitude) ?? (bTelemetry.environment_vectors[axis] && bTelemetry.environment_vectors[axis].magnitude) ?? 0;\n')
f.write('    const div = document.createElement("div");\n')
f.write('    div.className = "vector-item";\n')
f.write('    div.innerHTML = `<span class="axis">${labels[i]}</span><span class="magnitude">${magnitude.toFixed(2)}</span>`;\n')
f.write('    grid.appendChild(div);\n')
f.write('  });\n')
f.write('  const vectorsTitle = grid.parentElement.querySelector("h3");\n')
f.write('  if (vectorsTitle) { vectorsTitle.textContent = "Environment Vectors E" + (isFallback ? " (Fallback)" : ""); }\n')
f.write('}\n')
f.write('\n')
f.write('function renderRegionalPassportsWidget(telemetry, isFallback = false) {\n')
f.write('  const { vectorGrid } = elements.panels;\n')
f.write('  if (!vectorGrid) return;\n')
f.write('  const regions = telemetry?.regions ?? bTelemetry.regionsb;\n')
f.write('  vectorGrid.innerHTML = "<h4>Regional Passports Grid (5 Ukrainian Regions)</h4>";\n')
f.write('  regions.forEach(region => {\n')
f.write('    const statusColor = region.status === "good" ? "#6bcb77" : region.status === "partial" ? "#ffd93d" : "#ff6b6b";\n')
f.write('    const div = document.createElement("div");\n')
f.write('    div.innerHTML = `<div class="region-card" style="border-left: 4px solid ${statusColor}"><strong>${region.name}</strong> (${region.code})<div style="font-size: 0.8em; margin-top: 4px">Status: <span style="color: ${statusColor}">${region.status}</span><br>Tension: <span style="color: #888">${region.social_tension}</span></div></div>`;\n')
f.write('    vectorGrid.appendChild(div);\n')
f.write('  });\n')
f.write('}\n')
f.write('\n')
f.write('function renderOsintSignalsWidget(telemetry, isFallback = false) {\n')
f.write('  const { signalsSection } = elements.panels;\n')
f.write('  if (!signalsSection) return;\n')
f.write('  const signals = telemetry?.active_signals_feed ?? bTelemetry.active_signals_feed;\n')
f.write('  const badge = document.createElement("span");\n')
f.write('  badge.className = "badge";\n')
f.write('  badge.id = "b-count";\n')
f.write('  badge.textContent = signals.length;\n')
f.write('  signalsSection.innerHTML = `<h4>Live OSINT Signals Feed <span class="badge" id="b-count">${signals.length}</span></h4><div class="b-list">${signals.map(s => "<div class=b-item><strong>" + s.signal_id + "</strong>: " + s.raw_text + "</div>").join("")}</div>`;\n')
f.write('  if (!isFallback) { signalsSection.innerHTML += "<p class=b-note>Auto-refresh every 15s | " + signals.length + " active signals</p>"; }\n')
f.write('}\n')
f.write('\n')
f.close()
