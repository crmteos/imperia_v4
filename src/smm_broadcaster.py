"""src/smm_broadcaster.py - Social Media Broadcaster.

Asynchronous multi-platform publisher that formats telemetry, alerts,
and generated intelligence reports from Kancelyariya Facade into
structured social posts (Telegram, Webhooks, Markdown feeds).

Supports dry-run mode for offline/test environments.
"""

import asyncio
import json
import logging
from datetime import datetime, timezone
from typing import Dict, List, Optional, Any

logger = logging.getLogger("smm_broadcaster")


class SMMBroadcaster:
    """Asynchronous social media broadcaster supporting Telegram, Webhooks, and Markdown feeds."""

    async def broadcast_markdown_feed(self, message: str, filename: Optional[str] = None) -> dict:
        """Broadcast a message to a Markdown feed file."""
        feed_path = self.config.get("markdown_feed_path", "docs/telemetry_feed.json")
        if filename:
            feed_path = filename

        if self.dry_run:
            result = {
                "status": "dry_run",
                "platform": "markdown_feed",
                "filename": feed_path,
                "message_preview": message[:100] + "..." if len(message) > 100 else message,
            }
            self.sent_messages.append(result)
            logger.info(f"[DRY-RUN] Markdown feed write to {feed_path}")
            return result

        try:
            import os
            os.makedirs(os.path.dirname(feed_path), exist_ok=True)

            feed_data = ""
            if os.path.exists(feed_path):
                with open(feed_path, "r", encoding="utf-8") as f:
                    feed_data = f.read()

            timestamp = datetime.now(timezone.utc).isoformat()
            new_entry = f"- [{timestamp}] {message}\n"

            if feed_data:
                updated = feed_data.rstrip() + new_entry
            else:
                updated = new_entry

            with open(feed_path, "w", encoding="utf-8") as f:
                f.write(updated)

            result = {
                "status": "written",
                "platform": "markdown_feed",
                "filename": feed_path,
            }
            self.sent_messages.append(result)
            logger.info(f"Markdown feed written to {feed_path}")
            return result

        except Exception as e:
            logger.error(f"Failed to write markdown feed: {e}")
            raise

    async def broadcast_telemetry_update(self, telemetry_data: dict) -> Dict[str, Any]:
        """Format and broadcast a telemetry update from the Kancelyariya Facade."""
        results = {}
        message = self._format_telemetry_markdown(telemetry_data)

        if self.config.get("telegram_bot_token"):
            results["telegram"] = await self.broadcast_telegram(message)

        if self.config.get("webhook_url"):
            results["webhook"] = await self.broadcast_webhook(
                {"telemetry": telemetry_data, "message": message}
            )

        if self.config.get("markdown_feed_path"):
            results["markdown_feed"] = await self.broadcast_markdown_feed(message)

        return results

